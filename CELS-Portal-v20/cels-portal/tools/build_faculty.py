#!/usr/bin/env python3
"""Build data/faculty.js (teacher photos, full names, aliases) from the faculty workbook.

Usage: python3 tools/build_faculty.py path/to/CELS_Faculty.xlsx

Columns used: Name (the name used in the schedule, "Fritzie (Zie)" means nickname Zie), Full Name, Position, Photo.
Emails in the workbook are deliberately NOT copied: data/faculty.js is readable by every visitor.
Role and profile link come from https://cels.lcic.edu.ph/faculty/ for the people listed there (SITE below); everyone else is "Teacher".
"""
import sys, re, json, os, warnings
import openpyxl
warnings.filterwarnings("ignore")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = {  # schedule name -> (role, profile page) as listed on https://cels.lcic.edu.ph/faculty/ (checked Nov 12, 2026)
    "Erwin": ("Academic Coordinator", "https://cels.lcic.edu.ph/faculty/erwin-quiamco-lpt-tm1/"),
    "Jessa": ("Assistant Academic Coordinator", "https://cels.lcic.edu.ph/faculty/jessa-cervantes-maed-lpt-tm1/"),
    "Nympha": ("Curriculum Coordinator", "https://cels.lcic.edu.ph/faculty/nympha-tapao/"),
    "Joem": ("Admin & Event Coordinator", "https://cels.lcic.edu.ph/faculty/joemari-s-orbeso-lpt/"),
    "Jo": ("Compliance Coordinator", "https://cels.lcic.edu.ph/faculty/johnnamie-n-bentazal-lpt/"),
    "Jing": ("Assistant Professor", "https://cels.lcic.edu.ph/faculty/mary-fe-jing-a-gonzales-lpt/"),
    "Charles": ("Assistant Professor", "https://cels.lcic.edu.ph/faculty/charles-kim/"),
    "Jhon": ("Assistant Professor", "https://cels.lcic.edu.ph/faculty/jhonwindel-jhon-b-tibalan-lpt/"),
    "Mark": ("Assistant Director", "https://cels.lcic.edu.ph/faculty/mark-ryen-anderson-m-ed/"),
}
ws = openpyxl.load_workbook(sys.argv[1]).active
head = [str(c.value).strip() for c in ws[1]]
col = {h: i for i, h in enumerate(head)}
people, aliases = {}, {}
for r in ws.iter_rows(min_row=2, values_only=True):
    if not r[col["Name"]]: continue
    raw = str(r[col["Name"]]).strip()
    m = re.match(r"^(.*?)\s*\((.*?)\)\s*$", raw)
    key, nick = (m.group(1), m.group(2)) if m else (raw, None)
    if nick: aliases[nick] = key
    role, url = SITE.get(key, ("Teacher" if str(r[col["Position"]]).strip() == "teacher" else str(r[col["Position"]]).strip().title(), None))
    p = {"name": str(r[col["Full Name"]]).strip(), "role": role, "photo": str(r[col["Photo"]]).strip()}
    if url: p["url"] = url
    assert p["photo"].startswith("https://cels.lcic.edu.ph/"), (key, p["photo"])
    people[key] = p
out = ("/* Teacher photos and names for Free Talk / 1-on-1. Generated by tools/build_faculty.py from CELS_Faculty.xlsx; profile links and roles from https://cels.lcic.edu.ph/faculty/.\n"
       "   Keys are the names used in the schedule. aliases: other names used for the same person. Teachers not listed keep the initials badge.\n"
       "   Photos load from the CELS website; if one fails to load the initials badge is shown instead. */\n"
       "window.CELS_FACULTY=" + json.dumps({"site": "https://cels.lcic.edu.ph/faculty/", "aliases": aliases, "people": people}, ensure_ascii=False, indent=1) + ";\n")
open(os.path.join(ROOT, "data/faculty.js"), "w").write(out)
print("people:", len(people), "| aliases:", aliases, "| with site profile:", sum(1 for p in people.values() if "url" in p))
